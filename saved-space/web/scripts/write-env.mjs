// Writes src/app/core/env.generated.ts from environment variables. Only PUBLIC values go here:
// the project web address and the publishable key. Never put a secret key in the app.
import { writeFileSync } from 'node:fs';

const url = process.env.SS_SUPABASE_URL || 'https://iiyeyisdmafernjjxkzu.supabase.co';
const key = process.env.SS_SUPABASE_KEY || '';
const api = process.env.SS_API_BASE || '';
if (key && !key.startsWith('sb_publishable_') && !key.startsWith('eyJ') && !key.startsWith('test_')) {
  console.error('SS_SUPABASE_KEY must be the publishable (anon) key. Refusing to continue.');
  process.exit(1);
}
if (key.startsWith('sb_secret_')) {
  console.error('That is a secret key. Never use it in the app.');
  process.exit(1);
}
writeFileSync(
  new URL('../src/app/core/env.generated.ts', import.meta.url),
  `// Generated by scripts/write-env.mjs. Do not edit, do not commit.\n` +
    `export const SUPABASE_URL = ${JSON.stringify(url)};\n` +
    `export const SUPABASE_KEY = ${JSON.stringify(key)};\n` +
    `export const API_BASE = ${JSON.stringify(api)};\n`,
);
console.log('env.generated.ts written (key ' + (key ? 'set' : 'MISSING') + ')');
